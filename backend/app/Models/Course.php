<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasManyThrough;
use Illuminate\Support\Str;

class Course extends Model
{
    use HasFactory;

    public const STATUS_DRAFT = 'draft';
    public const STATUS_PUBLISHED = 'published';
    public const STATUS_ARCHIVED = 'archived';

    public const ALL_STATUSES = [
        self::STATUS_DRAFT,
        self::STATUS_PUBLISHED,
        self::STATUS_ARCHIVED,
    ];

    protected $fillable = [
        'teacher_id',
        'title',
        'slug',
        'description',
        'category',
        'price',
        'thumbnail_url',
        'status',
    ];

    protected function casts(): array
    {
        return [
            'price' => 'float',
        ];
    }

    /**
     * Auto-generate unique slug upon creation if not provided.
     */
    protected static function boot()
    {
        parent::boot();

        static::creating(function (Course $course) {
            if (empty($course->slug)) {
                $baseSlug = Str::slug($course->title);
                $candidate = $baseSlug;
                $counter = 1;
                while (self::where('slug', $candidate)->exists()) {
                    $candidate = "{$baseSlug}-" . Str::lower(Str::random(4)) . "-{$counter}";
                    $counter++;
                }
                $course->slug = $candidate;
            }
        });
    }

    /**
     * Teacher / Instructor who owns the course.
     */
    public function teacher(): BelongsTo
    {
        return $this->belongsTo(User::class, 'teacher_id');
    }

    /**
     * Curriculum modules / chapters.
     */
    public function modules(): HasMany
    {
        return $this->hasMany(CourseModule::class, 'course_id')->orderBy('order');
    }

    /**
     * All lessons across modules.
     */
    public function lessons(): HasManyThrough
    {
        return $this->hasManyThrough(CourseLesson::class, CourseModule::class, 'course_id', 'course_module_id');
    }

    /**
     * Enrollments records.
     */
    public function enrollments(): HasMany
    {
        return $this->hasMany(Enrollment::class, 'course_id');
    }

    /**
     * Orders placed for this course.
     */
    public function orders(): HasMany
    {
        return $this->hasMany(Order::class, 'course_id');
    }

    /**
     * Earnings generated by this course.
     */
    public function earnings(): HasMany
    {
        return $this->hasMany(TeacherEarning::class, 'course_id');
    }

    /**
     * Enrolled students.
     */
    public function students(): BelongsToMany
    {
        return $this->belongsToMany(User::class, 'enrollments', 'course_id', 'user_id')
            ->withPivot(['status', 'enrolled_at', 'progress_percentage'])
            ->withTimestamps();
    }

    /**
     * Scopes.
     */
    public function scopePublished(Builder $query): Builder
    {
        return $query->where('status', self::STATUS_PUBLISHED);
    }

    public function scopeByTeacher(Builder $query, int $teacherId): Builder
    {
        return $query->where('teacher_id', $teacherId);
    }

    public function scopeCategory(Builder $query, string $category): Builder
    {
        return $query->where('category', $category);
    }
}
