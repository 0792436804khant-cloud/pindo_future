<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class AppNotification extends Model
{
    use HasFactory;

    public const TYPE_LIVE_SESSION_STARTED = 'live_session_started';
    public const TYPE_LIVE_SESSION_STARTING = 'live_session_starting';
    public const TYPE_PAYMENT_CONFIRMED = 'payment_confirmed';
    public const TYPE_COURSE_ENROLLED = 'course_enrolled';
    public const TYPE_RECORDING_READY = 'recording_ready';
    public const TYPE_GUARDIAN_ALERT = 'guardian_alert';
    public const TYPE_TEACHER_VERIFIED = 'teacher_verified';

    protected $fillable = [
        'user_id',
        'type',
        'title',
        'body',
        'data',
        'read_at',
    ];

    protected function casts(): array
    {
        return [
            'data' => 'array',
            'read_at' => 'datetime',
        ];
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function scopeUnread(Builder $query): Builder
    {
        return $query->whereNull('read_at');
    }

    public function scopeForUser(Builder $query, int $userId): Builder
    {
        return $query->where('user_id', $userId);
    }

    public function markAsRead(): bool
    {
        if (is_null($this->read_at)) {
            return $this->update(['read_at' => now()]);
        }
        return true;
    }
}
